#!/usr/bin/env python3
"""Fetch the published saved-run of the MUB dimension-six verification and pin it.

The replay driver (replay.py) compares produced artefacts against the artefacts the
authors recorded.  Those artefacts are published under

    github.com/openai/math
    preprints/The-maximum-number-of-mutually-unbiased-bases-in-dimension-six-September-24-2026
    /verification/saved-run/

This script downloads every blob of that subtree into a local cache, checks each
download against the *git blob sha1* and byte size reported by the GitHub tree API
for branch `main`, and writes a manifest of sha256 digests next to itself.  The
manifest is what replay.py treats as the definition of "the recorded artefact".

Nothing here trusts the download: size and blob sha1 come from the API listing, so a
truncated or substituted file fails the check.  A later change upstream shows up as a
manifest mismatch rather than as a silent difference in the replay verdict.

Usage (one command; network needed):
    python3 work/10-recreate/harness/fetch_saved_run.py [--cache DIR] [--check]

    --cache DIR   cache directory (default: work/10-recreate/crew/m3/saved-run)
    --check       do not download; verify an existing cache against the manifest
Exit status: 0 = every file present and matching, 1 = anything missing or wrong.
"""
import argparse
import concurrent.futures
import hashlib
import json
import os
import sys
import urllib.error
import urllib.request

REPO = "openai/math"
BRANCH = "main"
PREFIX = ("preprints/The-maximum-number-of-mutually-unbiased-bases-in-dimension-six-"
          "September-24-2026/verification/saved-run")
# Pinned tree sha1 of the saved-run subtree at branch main.
TREE_SHA = "ccba22651c54a8681de6f2fec2d96867445f2180"
API = "https://api.github.com/repos/%s/git/trees/%s?recursive=1" % (REPO, TREE_SHA)
RAW = "https://raw.githubusercontent.com/%s/%s/%s" % (REPO, BRANCH, PREFIX)
HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
MANIFEST = os.path.join(HERE, "tampered.manifest.json")
DEFAULT_CACHE = os.path.join(REPO_ROOT, "work", "10-recreate", "crew", "m3", "saved-run")

# The four arun bad files are zero-length by design (spec/interfaces.md 3.3) and are
# still blobs of the tree; they are fetched like everything else.
WORKERS = 8


def blob_sha1(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def get(url, tries=4):
    last = None
    for attempt in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "mub-replay-harness"})
            with urllib.request.urlopen(req, timeout=120) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            last = e
            if e.code in (403, 429) and attempt + 1 < tries:
                continue
            raise
        except Exception as e:          # transient network
            last = e
    raise last


def listing():
    tree = json.loads(get(API))
    if tree.get("truncated"):
        sys.exit("FATAL: GitHub tree listing truncated; refusing a partial cache")
    blobs = {}
    for e in tree["tree"]:
        if e["type"] == "blob":
            blobs[e["path"]] = {"bytes": e["size"], "blob_sha1": e["sha"]}
    if not blobs:
        sys.exit("FATAL: empty tree listing")
    return blobs


def cached_ok(path, meta):
    if not os.path.exists(path):
        return False
    if os.path.getsize(path) != meta["bytes"]:
        return False
    with open(path, "rb") as f:
        return blob_sha1(f.read()) == meta["blob_sha1"]


def download(path, meta, cache):
    dest = os.path.join(cache, path)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    data = get("%s/%s" % (RAW, path))
    if len(data) != meta["bytes"]:
        return path, "size %d != %d" % (len(data), meta["bytes"])
    if blob_sha1(data) != meta["blob_sha1"]:
        return path, "blob sha1 %s != %s" % (blob_sha1(data), meta["blob_sha1"])
    tmp = dest + ".part"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, dest)
    return path, None


def build_manifest(blobs, cache):
    files = {}
    for path, meta in sorted(blobs.items()):
        with open(os.path.join(cache, path), "rb") as f:
            data = f.read()
        files[path] = {"bytes": len(data), "sha256": sha256(data),
                       "blob_sha1": meta["blob_sha1"]}
    man = {
        "source": {
            "repo": REPO, "branch": BRANCH, "path": PREFIX,
            "tree_sha1": TREE_SHA, "api": API, "raw": RAW,
        },
        "note": ("Generated by fetch_saved_run.py. sha256 is the digest of the published "
                 "bytes; blob_sha1 and bytes come from the GitHub tree listing and are "
                 "checked on every fetch. This file is the definition of 'the recorded "
                 "artefact' for replay.py."),
        "files": files,
    }
    with open(MANIFEST + ".part", "w") as f:
        json.dump(man, f, indent=1, sort_keys=True)
        f.write("\n")
    os.replace(MANIFEST + ".part", MANIFEST)
    return man


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=DEFAULT_CACHE)
    ap.add_argument("--check", action="store_true",
                    help="verify existing cache against the manifest, no download")
    args = ap.parse_args()
    cache = os.path.abspath(args.cache)

    if args.check:
        if not os.path.exists(MANIFEST):
            print("FAIL no manifest at " + MANIFEST)
            return 1
        man = json.load(open(MANIFEST))
        bad = []
        for path, meta in man["files"].items():
            p = os.path.join(cache, path)
            if not os.path.exists(p):
                bad.append((path, "missing"))
                continue
            data = open(p, "rb").read()
            if len(data) != meta["bytes"] or sha256(data) != meta["sha256"]:
                bad.append((path, "digest mismatch"))
        print(json.dumps({"mode": "check", "cache": cache, "files": len(man["files"]),
                          "bad": len(bad), "verdict": "PASS" if not bad else "FAIL",
                          "detail": bad[:20]}))
        return 0 if not bad else 1

    os.makedirs(cache, exist_ok=True)
    blobs = listing()
    print("listing: %d blobs, %d bytes" % (len(blobs), sum(m["bytes"] for m in blobs.values())),
          flush=True)
    have = [p for p, m in blobs.items() if cached_ok(os.path.join(cache, p), m)]
    todo = [(p, m) for p, m in sorted(blobs.items()) if p not in have]
    print("cache %s: %d already verified, %d to fetch" % (cache, len(have), len(todo)),
          flush=True)
    errors = []
    if todo:
        with concurrent.futures.ThreadPoolExecutor(max_workers=WORKERS) as ex:
            futs = {ex.submit(download, p, m, cache): p for p, m in todo}
            done = 0
            for fut in concurrent.futures.as_completed(futs):
                path, err = fut.result()
                done += 1
                if err:
                    errors.append((path, err))
                if done % 25 == 0 or done == len(todo):
                    print("  %d/%d" % (done, len(todo)), flush=True)
    if errors:
        print(json.dumps({"mode": "fetch", "cache": cache, "errors": errors,
                          "verdict": "FAIL"}))
        return 1
    man = build_manifest(blobs, cache)
    total = sum(v["bytes"] for v in man["files"].values())
    print(json.dumps({"mode": "fetch", "cache": cache, "manifest": MANIFEST,
                      "files": len(man["files"]), "bytes": total,
                      "verdict": "PASS"}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
