#!/usr/bin/env python3
"""audit/audit.py — mechanised statement audit for T4 (m1).

The fidelity table (`reports/statements-m1.md`) and the status table (`reports/status-m1.md`) are
generated here, so that neither can drift from what Lean actually checked.

What is hand-written: `audit/spec.py` — one row per in-scope declaration, carrying the paper
locator, the verbatim quote, the binder-by-binder audit, the deliberate changes, and how a
code-dependence was turned into a hypothesis.

What is machine-derived, per declaration:
  * whether it elaborates in this tree at all;
  * its type, as printed by `#check @name` — the evidence for the "binder agreement" column;
  * its axiom footprint, as printed by `#print axioms`, which also reveals `sorryAx`
    (transitively: a declaration that uses one which uses `sorry` inherits `sorryAx`).

Usage:  python3 audit/audit.py            (from the directory that holds Mub6/ and Audit/)
"""
import os
import subprocess
import sys
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import spec  # noqa: E402

MARK = "==AUDIT-END=="

# Modules are compiled in dependency order so that each import resolves against `.build-m1`.
BUILD_ORDER = ["Mub6.Basic", "Mub6.Gap", "Mub6.Hypotheses", "Mub6.Hadamard", "Mub6.Frames",
               "Mub6.Ellipsoid", "Mub6.Exclusion", "Mub6.ThreeMUB", "Mub6.Seed",
               "Mub6.Completion", "Mub6.Refine", "Mub6.Interface", "Mub6.Exclude",
               "Mub6.Assembly", "Mub6.AssemblyCover", "Mub6.AxiomCheck"]


def order(mods):
    known = [m for m in BUILD_ORDER if m in mods]
    return known + [m for m in mods if m not in BUILD_ORDER]


def modules(rows):
    mods = []
    for r in rows:
        m = r["module"]
        if m != "PENDING" and m not in mods:
            mods.append(m)
    return order(mods)


def write_dump(rows):
    """Emit Audit/Dump.lean: for each declaration, its elaborated type and its axioms."""
    lines = ["-- GENERATED by audit/audit.py — do not edit.",
             "-- Elaborates every in-scope declaration and dumps type + axiom footprint.",
             ""]
    for m in modules(rows):
        lines.append(f"import {m}")
    lines.append("")
    for r in rows:
        if r["module"] == "PENDING":
            continue
        d = r["decl"]
        lines.append(f'#eval IO.println "==AUDIT-BEGIN {d}"')
        lines.append(f"#check @{d}")
        lines.append(f'#eval IO.println "{MARK}"')
        lines.append(f"#print axioms {d}")
        lines.append(f'#eval IO.println "{MARK}"')
        lines.append("")
    path = ROOT / "Audit-m1" / "Dump.lean"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path


def build_oleans(rows):
    """Compile each module to `.build/`, one at a time.  Returns (root, {module: (rc, log)})."""
    bt = ROOT / ".build-m1"
    logs = {}
    # compile every module of the tree that exists, in dependency order, so imports resolve
    todo = [m for m in order(BUILD_ORDER + modules(rows))
            if (ROOT / (m.replace(".", "/") + ".lean")).exists()]
    for m in todo:
        rel = m.replace(".", "/") + ".lean"
        out = bt / (m.replace(".", "/") + ".olean")
        out.parent.mkdir(parents=True, exist_ok=True)
        env = dict(os.environ)
        env["LEAN_PATH"] = f"{bt}:{ROOT}:" + env.get("LEAN_PATH", "")
        p = subprocess.run(["lean", "-o", str(out), rel], capture_output=True, text=True,
                           cwd=ROOT, env=env)
        logs[m] = (p.returncode, p.stdout + p.stderr)
    return bt, logs


def run_lean(path, bt):
    env = dict(os.environ)
    env["LEAN_PATH"] = f"{bt}:{ROOT}:" + env.get("LEAN_PATH", "")
    p = subprocess.run(["lean", str(path)], capture_output=True, text=True, cwd=ROOT, env=env)
    return p.returncode, p.stdout + p.stderr


def parse(out):
    """Split the dump output into per-declaration (type, axioms) pairs."""
    res = {}
    for block in out.split("==AUDIT-BEGIN "):
        if not block.strip() or block.startswith("--"):
            continue
        name, _, rest = block.partition("\n")
        name = name.strip()
        parts = rest.split(MARK)
        typ = parts[0].strip() if parts else ""
        ax = parts[1].strip() if len(parts) > 1 else ""
        ok = "error" not in typ and "Unknown identifier" not in typ and typ != ""
        res[name] = (ok, typ, ax)
    return res


def sorry_of(ax):
    return "sorryAx" in ax


def clean_ax(ax):
    if not ax:
        return "?"
    if "does not depend on any axioms" in ax:
        return "none"
    if "depends on axioms" in ax:
        s = ax.split("[", 1)[-1].rsplit("]", 1)[0]
        return ", ".join(x.strip() for x in s.split(",") if x.strip())
    return ax.replace("\n", " ")


def md_escape(s):
    return s.replace("|", "\\|").replace("\n", " ")


def paper_rows(rows):
    return [r for r in rows if r["module"] != "PENDING" and not r.get("note", "").startswith("infra")
            and not r.get("note", "").startswith("hypothesis")]


def render_statements(rows, parsed):
    L = []
    L.append("# Statement fidelity table (generated)")
    L.append("")
    L.append("Generated by `audit/audit.py` from `audit/spec.py` (hand-written paper-side columns)")
    L.append("and from Lean itself (elaborated type and axiom footprint). Regenerate with")
    L.append("`python3 audit/audit.py`; do not edit by hand.")
    L.append("")
    L.append("Status of this section: `Mub6/Gap.lean` and `Mub6/Hypotheses.lean` are present in this")
    L.append("tree. Rows marked `PENDING` are in scope for T4 phase 0 but are stated by a sibling")
    L.append("direction and are not in this tree; their paper-side columns are complete and their")
    L.append("Lean-side columns fill in automatically when the driver is run over the merged tree.")
    L.append("")
    L.append("## 1. Rows")
    L.append("")
    L.append("| Lean name | module | paper locator | tag | compiles | axiom footprint |")
    L.append("|---|---|---|---|---|---|")
    for r in rows:
        d = r["decl"]
        if r["module"] == "PENDING":
            L.append(f"| `{d}` | PENDING ({md_escape(r.get('owner',''))}) | {r['paper']} | "
                     f"{r['tag']} | no (not in this tree) | — |")
        else:
            ok, typ, ax = parsed.get(d.lstrip("~"), (False, "", ""))
            L.append(f"| `{d}` | {r['module']} | {r['paper']} | {r['tag']} | "
                     f"{'yes' if ok else 'NO'} | {md_escape(clean_ax(ax))} |")
    L.append("")
    L.append("## 2. Binder-by-binder audit")
    L.append("")
    L.append("For each declaration: the paper's statement verbatim, then the audit of quantifier")
    L.append("order, carriers, shared witnesses, endpoints and strength of conclusion, then any")
    L.append("deliberate strengthening or weakening, then the disposition of a code-dependence.")
    L.append("")
    for r in rows:
        d = r["decl"]
        L.append(f"### `{d}` — {r['paper']}  [tag {r['tag']}]")
        L.append("")
        L.append(f"- **Paper:** {r['quote']}")
        L.append(f"- **Binders:** {r['binders']}")
        L.append(f"- **Deliberate change:** {r['changes']}")
        L.append(f"- **Code-dependence -> hypothesis:** {r['code_dep']}")
        if r["module"] == "PENDING":
            L.append(f"- **Lean side:** PENDING — owned by {r.get('owner','')}; run this driver over "
                     f"the merged tree to fill in the type and the axiom footprint.")
        else:
            ok, typ, ax = parsed.get(d.lstrip("~"), (False, "", ""))
            L.append(f"- **Elaborated type:**")
            L.append("")
            L.append("```lean")
            L.append(typ)
            L.append("```")
            L.append("")
            L.append(f"- **Axioms:** {clean_ax(ax)}")
        L.append("")
    return "\n".join(L) + "\n"


def render_status(rows, parsed, returncode, raw_errors):
    L = []
    L.append("# Proof status (generated — separate from source fidelity)")
    L.append("")
    L.append("This table answers ONE question per declaration: what does Lean accept? It says")
    L.append("nothing about whether the statement matches the paper; that is `reports/statements-m1.md`.")
    L.append("The two are never merged into one judgement.")
    L.append("")
    L.append(f"Dump run: `lean Audit-m1/Dump.lean` -> exit {returncode}.")
    L.append("")
    L.append("Axiom footprint key: `none` = proved outright; `propext, Classical.choice, Quot.sound`")
    L.append("= only Lean's standard axioms (the normal footprint of ordinary mathematics);")
    L.append("`sorryAx` = the declaration is STATED ONLY (it, or something it uses, has a hole).")
    L.append("")
    L.append("## 1. Declarations present in this tree")
    L.append("")
    L.append("| declaration | module | compiles | remaining goals | axiom footprint |")
    L.append("|---|---|---|---|---|")
    for r in rows_to_show(rows, parsed):
        d = r["decl"]
        ok, typ, ax = parsed[d]
        goals = "1+ (sorryAx)" if sorry_of(ax) else "0"
        L.append(f"| `{d}` | {r['module']} | {'yes' if ok else 'NO'} | {goals} | "
                 f"{md_escape(clean_ax(ax))} |")
    L.append("")
    L.append("## 2. Declarations in scope but not in this tree")
    L.append("")
    L.append("| declaration | paper locator | owner |")
    L.append("|---|---|---|")
    for r in rows:
        if r["module"] == "PENDING":
            L.append(f"| `{r['decl']}` | {r['paper']} | {r.get('owner','')} |")
    L.append("")
    L.append("## 3. Elaboration diagnostics")
    L.append("")
    if raw_errors.strip():
        L.append("```")
        L.append(raw_errors.strip()[:4000])
        L.append("```")
    else:
        L.append("No errors and no warnings.")
    L.append("")
    return "\n".join(L) + "\n"


def rows_to_show(rows, parsed):
    out = []
    for r in rows:
        if r["module"] == "PENDING":
            continue
        if r["decl"].lstrip("~") in parsed:
            out.append(r)
    return out


def main():
    rows = spec.ROWS
    bt, logs = build_oleans(rows)
    path = write_dump(rows)
    rc, out = run_lean(path, bt)
    (ROOT / "Audit-m1" / "dump.txt").write_text(out)
    parsed = parse(out)
    errs = "\n".join(l for l in out.splitlines()
                     if "error" in l or "warning" in l)
    for m, (mrc, mlog) in logs.items():
        if mrc != 0:
            errs += f"\n[{m}] exit {mrc}\n" + mlog
    rep = ROOT / "reports"
    rep.mkdir(exist_ok=True)
    (rep / "statements-m1.md").write_text(render_statements(rows, parsed))
    (rep / "status-m1.md").write_text(render_status(rows, parsed, rc, errs))
    n_here = len(rows_to_show(rows, parsed))
    n_ok = sum(1 for r in rows_to_show(rows, parsed) if parsed[r["decl"]][0])
    print(f"rows: {len(rows)}  present: {n_here}  elaborate: {n_ok}  "
          f"pending: {len(rows) - n_here}")
    for m, (mrc, _) in logs.items():
        print(f"  module {m}: exit {mrc}")
    for d, (ok, typ, ax) in parsed.items():
        if not ok:
            print(f"  FAILED: {d}")
    print(f"lean exit {rc}")
    return 0 if rc == 0 or n_ok == n_here else 1


if __name__ == "__main__":
    sys.exit(main())
