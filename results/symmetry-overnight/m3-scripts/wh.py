"""Weyl-Heisenberg group over Z_6 acting on C^6, exact matrices over Z[zeta_24].

Conventions:  X e_j = e_{j+1 mod 6},  Z e_j = omega^j e_j,  omega = zeta_24^4.
W(a,b) = X^a Z^b,  and X^a Z^b = omega^{ab} Z^b X^a.
Group: elements (theta, a, b) meaning omega^theta * W(a,b), all in Z_6.
"""
from zeta import *

N = 6
IDX = range(N)

def Xmat(a):
    M = [[ZERO]*N for _ in range(N)]
    for j in IDX:
        M[(j+a) % N][j] = ONE
    return M

def Zmat(b):
    M = [[ZERO]*N for _ in range(N)]
    for j in IDX:
        M[j][j] = POW[(4*b*j) % 24]     # omega^{b j}
    return M

def matmul(A, B):
    n = len(A)
    return [[sum_( [mul(A[i][k], B[k][j]) for k in range(n)] ) for j in range(n)] for i in range(n)]

def sum_(xs):
    r = ZERO
    for x in xs:
        r = add(r, x)
    return r

def Wmat(a, b):
    return matmul(Xmat(a), Zmat(b))

def Wmat_pow(a, b):
    """X^a as permutation matrix."""
    return Xmat(a)

# group law:  (t,a,b)(s,c,d) = (t+s + b*c, a+c, b+d)   [omega^{a'b} factor]
def glaw(g, h):
    t, a, b = g
    s, c, d = h
    return ((t+s + b*c) % 6, (a+c) % 6, (b+d) % 6)

def gmul(g, h):
    return glaw(g, h)

def ginv(g):
    t, a, b = g
    # inverse of omega^t W(a,b): (omega^t W)^{-1} = omega^{-t} W(a,b)^{-1}; W(a,b)^{-1}= omega^{-ab}(-a,-b)
    return ((-t - a*(-b)) % 6, (-a) % 6, (-b) % 6)

def gcomm(g, h):
    """commutator g h g^-1 h^-1"""
    return glaw(glaw(glaw(g, h), ginv(g)), ginv(h))

GROUP = [(t, a, b) for t in range(6) for a in range(6) for b in range(6)]

def subgroup_closure(gens):
    S = {(0, 0, 0)}
    frontier = [(0, 0, 0)]
    gens = list(gens)
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                k = glaw(g, h)
                if k not in S:
                    S.add(k)
                    new.append(k)
        frontier = new
    return frozenset(S)

def is_abelian(S):
    L = sorted(S)
    for i in range(len(L)):
        for j in range(i+1, len(L)):
            if glaw(L[i], L[j]) != glaw(L[j], L[i]):
                return False
    return True

